<?php

declare(strict_types=1);

namespace Weline\Geo\Service\Protocol;

/**
 * Industry AI discovery and usage-permission documents other than llms.txt.
 *
 * Posture: search, AI input (grounding / citation) and AI training are all
 * allowed; only junk SEO/scraper bots are kept out, and that happens in
 * robots.txt through the per-site crawler policy, not here. TDMRep stays
 * reservation 0 for the same open posture. ai.txt, trust.txt, Content-Signal
 * ai-train=yes and RSL permits all declare the permission explicitly.
 */
final class IndustryProtocolDocuments
{
    public static function aiTxt(): string
    {
        return implode("\n", [
            '# Generated by Weline_Geo',
            '# Spawning ai.txt: commercial AI training permitted. This file is not llms.txt.',
            'User-Agent: *',
            'Allow: /',
            '',
        ]);
    }

    public static function licenseXml(bool $aiInputAllowed): string
    {
        $usage = $aiInputAllowed ? 'search ai-input ai-train' : 'search ai-train';

        return '<?xml version="1.0" encoding="UTF-8"?>' . "\n"
            . '<rsl xmlns="https://rslstandard.org/rsl">' . "\n"
            . '  <content url="/">' . "\n"
            . '    <license>' . "\n"
            . '      <permits type="usage">' . $usage . '</permits>' . "\n"
            . '    </license>' . "\n"
            . '  </content>' . "\n"
            . '</rsl>' . "\n";
    }

    public static function tdmRepJson(): string
    {
        $json = json_encode([
            [
                'location' => '/',
                'tdm-reservation' => 0,
            ],
        ], JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);

        return (is_string($json) ? $json : '[]') . "\n";
    }

    public static function trustTxt(string $baseUrl): string
    {
        $lines = [
            '# Generated by Weline_Geo',
        ];
        $member = rtrim(trim($baseUrl), '/');
        if (preg_match('#^https?://#i', $member) === 1 && !str_contains($member, "\n")) {
            $lines[] = 'member=' . $member;
        }
        $lines[] = 'datatrainingallowed=yes';
        $lines[] = '';

        return implode("\n", $lines);
    }

    /**
     * @return list<string>
     */
    public static function llmsDiscoveryLines(string $baseUrl, bool $feedEnabled): array
    {
        $baseUrl = rtrim(trim($baseUrl), '/');
        if ($baseUrl === '' || preg_match('#^https?://#i', $baseUrl) !== 1) {
            return [];
        }

        $lines = [
            '- Sitemap: ' . $baseUrl . '/sitemap.xml',
            '- llms-full.txt: ' . $baseUrl . '/llms-full.txt',
            '- ai.txt: ' . $baseUrl . '/ai.txt',
            '- RSL license: ' . $baseUrl . '/license.xml',
            '- trust.txt: ' . $baseUrl . '/trust.txt',
            '- TDMRep: ' . $baseUrl . '/.well-known/tdmrep.json',
            '- Agent catalog (ARD): ' . $baseUrl . '/.well-known/ard.json',
            '- Agent catalog (ai-catalog): ' . $baseUrl . '/.well-known/ai-catalog.json',
        ];
        if ($feedEnabled) {
            $lines[] = '- JSON Feed: ' . $baseUrl . '/geo-feed.json';
            $lines[] = '- RSS Feed: ' . $baseUrl . '/geo-feed.xml';
        }

        return $lines;
    }

    /**
     * Robots.txt lines contributed by Geo. The RSL license is a comment because
     * REP has no License directive and search consoles report it as unknown;
     * Content-Signal belongs in the User-agent: * group.
     *
     * @return array{global_lines: list<string>, star_lines: list<string>}
     */
    public static function robotsContribution(string $baseUrl, bool $robotsEnabled, bool $aiInputAllowed): array
    {
        $global = [];
        $licenseUrl = rtrim(trim($baseUrl), '/');
        if (preg_match('#^https?://#i', $licenseUrl) === 1 && !preg_match('/[\r\n\s]/', $licenseUrl)) {
            $global[] = '# RSL license: ' . $licenseUrl . '/license.xml';
        }

        $search = $robotsEnabled ? 'yes' : 'no';
        $aiInput = $robotsEnabled && $aiInputAllowed ? 'yes' : 'no';
        $aiTrain = $robotsEnabled ? 'yes' : 'no';

        return [
            'global_lines' => $global,
            // Content-Signal is not a standard robots.txt directive; Lighthouse / Google
            // Search Console flag the bare form as "Unknown directive". Keep the signal as
            // a comment so crawlers still see the intent without failing SEO audits.
            'star_lines' => [
                '# Content-Signal: https://contentsignals.org/',
                '# Content-Signal: search=' . $search . ', ai-input=' . $aiInput . ', ai-train=' . $aiTrain,
            ],
        ];
    }

    public static function headHtml(string $baseUrl, string $title, bool $llmsEnabled, bool $feedEnabled): string
    {
        $baseUrl = rtrim(trim($baseUrl), '/');
        $title = self::escape($title !== '' ? $title : 'GEO');
        $lines = ['<meta name="tdm-reservation" content="0">'];
        if ($baseUrl !== '') {
            $license = self::escape($baseUrl . '/license.xml');
            $lines[] = '<link rel="license" type="application/rsl+xml" href="' . $license . '">';
            $lines[] = '<link rel="alternate" type="text/plain" title="' . $title . ' ai.txt" href="' . self::escape($baseUrl . '/ai.txt') . '">';
            $lines[] = '<link rel="alternate" type="text/plain" title="' . $title . ' trust.txt" href="' . self::escape($baseUrl . '/trust.txt') . '">';
            $lines[] = '<link rel="describedby" type="application/json" title="' . $title . ' tdmrep.json" href="' . self::escape($baseUrl . '/.well-known/tdmrep.json') . '">';
        }
        if ($feedEnabled && $baseUrl !== '') {
            $lines[] = '<link rel="alternate" type="application/feed+json" title="' . $title . ' JSON Feed" href="' . self::escape($baseUrl . '/geo-feed.json') . '">';
            $lines[] = '<link rel="alternate" type="application/rss+xml" title="' . $title . ' RSS Feed" href="' . self::escape($baseUrl . '/geo-feed.xml') . '">';
        }
        if ($llmsEnabled && $baseUrl !== '') {
            $lines[] = '<link rel="alternate" type="text/plain" title="' . $title . ' llms.txt" href="' . self::escape($baseUrl . '/llms.txt') . '">';
            $lines[] = '<link rel="alternate" type="text/plain" title="' . $title . ' llms-full.txt" href="' . self::escape($baseUrl . '/llms-full.txt') . '">';
        }
        if ($baseUrl !== '') {
            // ARD v0.91 (agenticresourcediscovery.org):
            // - rel="ard" is the normative link; type MUST be application/ai-catalog+json
            //   for a hosted entry manifest (application/ai-registry+json is ONLY for
            //   search-registry service cards — validators treat that MIME as a registry
            //   document and reject our catalog body as "schema invalid / cannot load").
            // - rel="ai-catalog" is the predecessor consumers MAY honour.
            $lines[] = '<link rel="ard" type="application/ai-catalog+json" href="' . self::escape($baseUrl . '/.well-known/ard.json') . '">';
            $lines[] = '<link rel="ai-catalog" type="application/ai-catalog+json" href="' . self::escape($baseUrl . '/.well-known/ai-catalog.json') . '">';
        }

        return implode("\n", $lines);
    }

    /**
     * ARD agent catalog manifest (ai-catalog.schema.json, specVersion 1.0).
     * Served at /.well-known/ai-catalog.json (predecessor) and /.well-known/ard.json.
     *
     * @param array{entries:list<array<string,mixed>>} $entries Prebuilt ARD catalog entries.
     */
    public static function aiCatalogJson(array $entries, string $baseUrl): string
    {
        $manifest = [
            'specVersion' => '1.0',
            'entries' => array_values($entries),
        ];
        $host = rtrim(trim($baseUrl), '/');
        if ($host !== '' && preg_match('#^https?://#i', $host) === 1) {
            $manifest['host'] = [
                'displayName' => parse_url($host, PHP_URL_HOST) ?? $host,
                'documentationUrl' => $host . '/llms.txt',
            ];
        }

        $json = json_encode($manifest, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);

        return (is_string($json) ? $json : '{"specVersion":"1.0","entries":[]}') . "\n";
    }

    private static function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
