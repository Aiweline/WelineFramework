namespace Weline\Framework\Setup\Shell;

use Weline\Framework\App\Env;

/**
 * 项目快捷命令（shell 函数）管理。
 *
 * - 同一个项目只保留一个别名：写入前先删除旧块与旧命令文件；
 * - shell 函数块（~/.zshrc 等）负责进入项目后保持当前目录；
 * - 同时写入已在 PATH 中的 ~/.local/bin/<名字> 可执行文件，改完立即可用，不需要 source；
 * - 块与可执行文件都带项目标记，改名/删除时一并清理；
 * - 身份规则：项目用户直接执行；root 直接切换（不输密码）；其他身份在 Linux 走 `su - 项目用户`
 *   （需要项目用户本人的密码），已有免密 sudo 授权的身份静默切换，macOS 非 root 走 sudo。
 */
class ShellAliasManager
{
    public const BEGIN_PREFIX = '# >>> Weline project command';
    public const END_MARKER = '# <<< Weline project command <<<';
    public const SCRIPT_PREFIX = '# Weline project command: ';
    public const SCRIPT_SUFFIX = ' (generated by php bin/w shell:alias)';
    public const PROMPT_TIMEOUT = 15;

    /** 系统级命令目录：写入后所有用户、任意 shell 免 source 可用。 */
    public const SYSTEM_BIN_DIRS = ['/usr/local/bin', '/usr/local/sbin'];

    private string $root;

    private string $home;

    public function __construct(?string $root = null, ?string $home = null)
    {
        $this->root = rtrim($root ?? (defined('BP') ? BP : dirname(__DIR__, 6)), '/\\');
        $this->home = rtrim($home ?? (string)(getenv('HOME') ?: ''), '/\\');
    }

    public function isSupported(): bool
    {
        return \PHP_OS_FAMILY !== 'Windows';
    }

    public function getRoot(): string
    {
        return $this->root;
    }

    /**
     * 目标 HOME 目录：当前 HOME + root 的 HOME（root 身份）+ sudo 发起用户的 HOME。
     *
     * @return list<string>
     */
    public function homes(bool $writableOnly = true): array
    {
        $candidates = [$this->home];
        if (function_exists('posix_geteuid') && posix_geteuid() === 0) {
            $candidates[] = $this->userHome('root');
        }
        $invoking = (string)(getenv('SUDO_USER') ?: '');
        if ($invoking !== '') {
            $candidates[] = $this->userHome($invoking);
        }
        $homes = [];
        foreach ($candidates as $candidate) {
            $candidate = rtrim($candidate, '/\\');
            if ($candidate === '' || !is_dir($candidate)) {
                continue;
            }
            if ($writableOnly && !is_writable($candidate)) {
                continue;
            }
            if (in_array($candidate, $homes, true)) {
                continue;
            }
            $homes[] = $candidate;
        }

        return $homes;
    }

    /**
     * 需要写入的 shell 配置文件。
     *
     * @return list<string>
     */
    public function shellFiles(?string $home = null): array
    {
        $home = rtrim($home ?? $this->home, '/\\');
        if ($home === '') {
            return [];
        }
        $files = [];
        foreach (['.zshrc', '.bashrc', '.bash_profile'] as $name) {
            $file = $home . DIRECTORY_SEPARATOR . $name;
            if (is_file($file)) {
                $files[] = $file;
            }
        }
        if ($files !== []) {
            return $files;
        }
        $preferZsh = \PHP_OS_FAMILY === 'Darwin' || str_contains((string)getenv('SHELL'), 'zsh');

        return [$home . DIRECTORY_SEPARATOR . ($preferZsh ? '.zshrc' : '.bashrc')];
    }

    /**
     * 查找本项目的快捷命令（改名前的旧命令也会被找到）。
     *
     * @return list<array{name: string, file: string}>
     */
    public function find(): array
    {
        $found = [];
        foreach ($this->homes(false) as $home) {
            foreach ($this->shellFiles($home) as $file) {
                if (!is_file($file)) {
                    continue;
                }
                $name = $this->readName($file);
                if ($name !== null) {
                    $found[] = ['name' => $name, 'file' => $file];
                }
            }
        }

        return $found;
    }

    /**
     * 可能存放项目命令文件的用户 bin / 系统级 bin 目录。
     *
     * @return list<string>
     */
    public function binDirs(): array
    {
        $dirs = [];
        foreach ($this->homes(false) as $home) {
            foreach ([$home . DIRECTORY_SEPARATOR . '.local' . DIRECTORY_SEPARATOR . 'bin', $home . DIRECTORY_SEPARATOR . 'bin'] as $dir) {
                if (is_dir($dir)) {
                    $dirs[] = $dir;
                }
            }
        }
        foreach (self::SYSTEM_BIN_DIRS as $dir) {
            if (is_dir($dir)) {
                $dirs[] = $dir;
            }
        }

        return array_values(array_unique($dirs));
    }

    /**
     * 查找本项目生成的命令文件（改名前的旧名字也会被找到）。
     *
     * @return list<array{name: string, file: string}>
     */
    public function findScripts(): array
    {
        $found = [];
        $marker = $this->scriptMarker();
        foreach ($this->binDirs() as $dir) {
            foreach (glob($dir . DIRECTORY_SEPARATOR . '*') ?: [] as $file) {
                if (!is_file($file) || !is_readable($file)) {
                    continue;
                }
                $name = basename($file);
                if (preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name) !== 1) {
                    continue;
                }
                $head = @file_get_contents($file, false, null, 0, 1024);
                if ($head === false || !str_contains($head, $marker)) {
                    continue;
                }
                $found[] = ['name' => $name, 'file' => $file];
            }
        }

        return $found;
    }

    /**
     * 可写命令目录候选：系统级目录优先（所有用户可用），其次 PATH 中的用户 bin。
     *
     * @return list<string>
     */
    private function scriptDirCandidates(): array
    {
        $ordered = [];
        foreach (self::SYSTEM_BIN_DIRS as $dir) {
            if (is_dir($dir) && is_writable($dir)) {
                $ordered[] = $dir;
            }
        }
        if ($this->home === '') {
            return $ordered;
        }
        $pathDirs = array_map(
            static fn (string $dir): string => rtrim($dir, '/\\'),
            explode(PATH_SEPARATOR, (string)getenv('PATH'))
        );
        $homeDirs = [
            $this->home . DIRECTORY_SEPARATOR . '.local' . DIRECTORY_SEPARATOR . 'bin',
            $this->home . DIRECTORY_SEPARATOR . 'bin',
        ];
        foreach ($homeDirs as $dir) {
            if (in_array($dir, $pathDirs, true) && is_dir($dir) && is_writable($dir)) {
                $ordered[] = $dir;
            }
        }
        foreach ($homeDirs as $dir) {
            $ordered[] = $dir;
        }

        return array_values(array_unique($ordered));
    }

    /**
     * 选择命令文件写入目录：可写，且同名文件要么不存在，要么是本项目生成的（避免覆盖他人命令）。
     */
    private function resolveScriptDir(string $name): ?string
    {
        foreach ($this->scriptDirCandidates() as $dir) {
            if (!is_dir($dir) && !@mkdir($dir, 0755, true)) {
                continue;
            }
            if (!is_writable($dir)) {
                continue;
            }
            $path = $dir . DIRECTORY_SEPARATOR . $name;
            if (file_exists($path) && !$this->isWelineScript($path)) {
                continue;
            }

            return $dir;
        }

        return null;
    }

    private function isWelineScript(string $path): bool
    {
        $head = @file_get_contents($path, false, null, 0, 1024);

        return is_string($head) && str_contains($head, self::SCRIPT_PREFIX);
    }

    /**
     * 是否由本项目生成的命令文件（标记里带本项目路径，可区分同族其他项目）。
     */
    private function isThisProjectScript(string $path): bool
    {
        $head = @file_get_contents($path, false, null, 0, 1024);

        return is_string($head) && str_contains($head, $this->scriptMarker());
    }

    /**
     * 写入（或改名）项目快捷命令；旧别名会先被移除，只保留一个。
     *
     * @param bool $allowPrompt 系统级安装需要授权时，是否当场询问 sudo 密码（TTY 下默认问）
     *
     * @return array{files: list<string>, script: ?string, errors: list<string>, warnings: list<string>, system: bool}
     */
    public function install(string $name, bool $allowPrompt = true): array
    {
        $error = self::validateName($name);
        if ($error !== null) {
            return ['files' => [], 'script' => null, 'errors' => [$error], 'warnings' => [], 'system' => false];
        }
        $homes = $this->homes();
        if ($homes === []) {
            return ['files' => [], 'script' => null, 'errors' => ['未找到可写的 HOME，无法写入 shell 配置。'], 'warnings' => [], 'system' => false];
        }

        $oldNames = array_values(array_unique(array_column($this->find(), 'name')));
        $block = $this->renderBlock($name);
        $pending = [];
        $errors = [];
        foreach ($homes as $home) {
            foreach ($this->shellFiles($home) as $file) {
                $content = '';
                if (is_file($file)) {
                    $content = @file_get_contents($file);
                    if ($content === false) {
                        $errors[] = '读取失败：' . $file;
                        continue;
                    }
                }
                if ($this->hasUnclosedBlock($content)) {
                    $errors[] = '已有未闭合的项目命令块，请先手动处理：' . $file;
                    continue;
                }
                $stripped = rtrim($this->stripBlock($content, $name), "\n");
                $pending[$file] = ($stripped === '' ? '' : $stripped . "\n\n") . $block . "\n";
            }
        }
        if ($errors !== []) {
            return ['files' => [], 'script' => null, 'errors' => $errors, 'warnings' => [], 'system' => false];
        }

        $written = [];
        foreach ($pending as $file => $content) {
            if (@file_put_contents($file, $content, LOCK_EX) === false) {
                $errors[] = '写入失败：' . $file;
                continue;
            }
            $written[] = $file;
        }

        $warnings = [];
        foreach ($this->findScripts() as $oldScript) {
            if (@unlink($oldScript['file'])) {
                continue;
            }
            if ($oldScript['name'] === $name) {
                // 同名的系统级命令交给 promoteToSystemBin 覆盖，这里不算删除失败
                continue;
            }
            $warnings[] = '旧命令文件删除失败（可能属于 root 或其他身份）：' . $oldScript['file']
                . '；需要删除请执行：sudo rm -f ' . $oldScript['file'];
        }
        $script = null;
        $system = false;
        $dir = $this->resolveScriptDir($name);
        if ($dir === null) {
            $warnings[] = '未找到可写命令目录（/usr/local/bin 或 ~/.local/bin），新命令需 source 或新终端后才可用。';
        } else {
            $scriptPath = $dir . DIRECTORY_SEPARATOR . $name;
            if (@file_put_contents($scriptPath, $this->renderScript($name), LOCK_EX) === false) {
                $errors[] = '写入失败：' . $scriptPath;
            } else {
                @chmod($scriptPath, 0755);
                $script = $scriptPath;
                $system = in_array($dir, self::SYSTEM_BIN_DIRS, true);
            }
        }
        if ($script !== null && !$system) {
            $promoteNotes = [];
            $promoted = $this->promoteToSystemBin($name, $script, $allowPrompt, $promoteNotes);
            if ($promoted !== null) {
                @unlink($script);
                $script = $promoted;
                $system = true;
            } else {
                foreach ($promoteNotes as $note) {
                    $warnings[] = $note;
                }
                $warnings[] = '该命令只对 ' . $this->deployUser() . ' 可见：其他身份（含 root）在 PATH 里找不到 ' . $name
                    . '；要全身份可用，请在自己的终端里执行 php bin/w shell:alias ' . $name
                    . '（不要加 --no-sudo），按提示输入 sudo 密码即完成系统级安装。';
            }
        }
        $invoking = (string)(getenv('SUDO_USER') ?: '');
        if ($invoking !== '' && $invoking !== $this->currentUser()) {
            $warnings[] = '本次由 ' . $invoking . ' 触发安装，但命令写入了 ' . $this->currentUser()
                . ' 的 HOME；' . $invoking . ' 的 shell 不会加载该函数，请按上面的 sudo install 安装系统级命令。';
        }
        foreach ($oldNames as $oldName) {
            if ($oldName !== $name) {
                $warnings[] = '当前终端若仍能执行旧命令 ' . $oldName . '，执行 unset -f ' . $oldName . '（或重开终端）即可。';
            }
        }

        return ['files' => $written, 'script' => $script, 'errors' => $errors, 'warnings' => $warnings, 'system' => $system];
    }

    /**
     * 把用户级命令文件提升为系统级，让任意身份都能在 PATH 中找到该命令。
     *
     * 已配免密 sudo 时静默安装；没有则当场询问授权（需 TTY）：输密码就装，不输就保持用户级。
     *
     * 系统目录里已有同名文件时的处置：
     * - 本项目生成的，内容一致 → 视为已安装，不再重复请求授权；
     * - 本项目生成的但内容过期 → 请求授权覆盖；
     * - 失效的（悬空符号链接 / 没有执行权限）→ 说明原因后请求授权替换，先删链接再装，绝不顺着链接写到别处；
     * - 其他项目正在使用的可执行命令 → 不覆盖，报告冲突并建议换命令名。
     *
     * @param list<string> $notes 供调用方展示的说明（授权提示、冲突原因、失败输出）
     */
    private function promoteToSystemBin(string $name, string $scriptPath, bool $allowPrompt, array &$notes = []): ?string
    {
        $passwordless = $this->passwordlessSudo();
        if (!$allowPrompt) {
            $notes[] = '已指定 --no-sudo，跳过系统级安装（命令只装在项目用户自己的 bin 目录）。';

            return null;
        }
        if (!$passwordless && !$this->isTty()) {
            $notes[] = '当前会话不是交互终端，无法当场请求 sudo 密码，跳过系统级安装；请在真实终端里重新执行本命令。';

            return null;
        }
        foreach (self::SYSTEM_BIN_DIRS as $dir) {
            if (!is_dir($dir) || is_writable($dir)) {
                continue;
            }
            $target = $dir . DIRECTORY_SEPARATOR . $name;
            $ours = $this->isThisProjectScript($target);
            if ($ours && @file_get_contents($target) === $this->renderScript($name)) {
                return $target;
            }
            $mustRemove = false;
            if (!$ours && (is_link($target) || file_exists($target))) {
                $linkTarget = is_link($target) ? (string)@readlink($target) : '';
                if ($linkTarget !== '' && !file_exists($target)) {
                    $mustRemove = true;
                    $notes[] = $target . ' 是失效的符号链接（指向 ' . $linkTarget . '，目标已不存在）。';
                } elseif (!is_executable($target)) {
                    $mustRemove = true;
                    $notes[] = $target . ' 已存在但没有执行权限（' . sprintf('%04o', (int)@fileperms($target) & 0777)
                        . '），任何身份都跑不起来。';
                } else {
                    $notes[] = $target . ' 已被另一个项目的命令占用'
                        . ($linkTarget !== '' ? '（符号链接 → ' . $linkTarget . '）' : '')
                        . '，为免破坏它没有覆盖；请换个命令名，例如：php bin/w shell:alias ' . $name . '-weline';

                    continue;
                }
            }
            if (!$passwordless) {
                fwrite(STDOUT, PHP_EOL . '为让 root / 其他身份也能直接运行 ' . $name . '，需要把它装到 ' . $target . PHP_EOL);
                foreach ($notes as $note) {
                    fwrite(STDOUT, '  · ' . $note . PHP_EOL);
                }
                fwrite(STDOUT, '现在请求授权（请输入当前身份的 sudo 密码，直接按回车可跳过）：' . PHP_EOL);
            }
            $output = [];
            $status = 1;
            $sudo = $this->sudoBinary() . ($passwordless ? ' -n' : '');
            if ($mustRemove) {
                @exec(
                    $sudo . ' ' . escapeshellarg($this->absoluteTool(['/bin/sh', '/usr/bin/sh'], 'sh')) . ' -c '
                    . escapeshellarg($this->replaceCommand()) . ' _ '
                    . escapeshellarg($target) . ' ' . escapeshellarg($scriptPath) . ' 2>&1',
                    $output,
                    $status
                );
            } else {
                @exec(
                    $sudo . ' ' . escapeshellarg($this->installBinary()) . ' -m 0755 '
                    . escapeshellarg($scriptPath) . ' ' . escapeshellarg($target) . ' 2>&1',
                    $output,
                    $status
                );
            }
            if ($status === 0 && is_file($target) && is_readable($target)) {
                if (!$passwordless) {
                    fwrite(STDOUT, '已安装到 ' . $target . '：任意身份、任意 shell 免 source 可用。' . PHP_EOL);
                }

                return $target;
            }
            $detail = trim(implode(' | ', array_slice($output, -2)));
            if ($detail !== '') {
                $notes[] = '安装命令输出：' . $detail;
            }
            if (!$passwordless) {
                fwrite(STDOUT, '未获得授权，' . $name . ' 暂时只装在 ' . $scriptPath . '（仅 ' . $this->deployUser() . ' 可用）。' . PHP_EOL);
            }

            return null;
        }

        return null;
    }

    /**
     * 删除系统级命令文件：root 所有时需要当场询问授权。
     */
    private function sudoRemove(string $path, bool $allowPrompt): bool
    {
        foreach (self::SYSTEM_BIN_DIRS as $dir) {
            if (!str_starts_with($path, $dir . DIRECTORY_SEPARATOR)) {
                continue;
            }
            $passwordless = $this->passwordlessSudo();
            if (!$passwordless && (!$allowPrompt || !$this->isTty())) {
                return false;
            }
            if (!$passwordless) {
                fwrite(STDOUT, PHP_EOL . '删除系统级命令 ' . $path . ' 需要授权（请输入当前身份的 sudo 密码）：' . PHP_EOL);
            }
            $output = [];
            $status = 1;
            @exec(
                $this->sudoBinary() . ($passwordless ? ' -n' : '') . ' '
                . escapeshellarg($this->rmBinary()) . ' -f ' . escapeshellarg($path) . ' 2>&1',
                $output,
                $status
            );

            return $status === 0 && !file_exists($path);
        }

        return false;
    }

    private function passwordlessSudo(): bool
    {
        if (!function_exists('exec') || !function_exists('posix_geteuid') || posix_geteuid() === 0) {
            return false;
        }
        $output = [];
        $status = 1;
        @exec($this->sudoBinary() . ' -n true 2>/dev/null', $output, $status);

        return $status === 0;
    }

    /**
     * 先删目标再安装的 shell 片段（$1 = 目标路径，$2 = 源文件）。
     *
     * 必须用绝对路径：本机实测 PATH 里的 install 会被其他项目的同名脚本遮蔽，
     * 而 /etc/sudoers 没有 secure_path 时 sudo 不会重置 PATH。
     */
    private function replaceCommand(): string
    {
        return escapeshellarg($this->rmBinary()) . ' -f "$1" && '
            . escapeshellarg($this->installBinary()) . ' -m 0755 "$2" "$1"';
    }

    private function installBinary(): string
    {
        return $this->absoluteTool(['/usr/bin/install', '/bin/install', '/usr/sbin/install'], 'install');
    }

    private function rmBinary(): string
    {
        return $this->absoluteTool(['/bin/rm', '/usr/bin/rm'], 'rm');
    }

    private function sudoBinary(): string
    {
        return $this->absoluteTool(['/usr/bin/sudo', '/bin/sudo', '/usr/local/bin/sudo'], 'sudo');
    }

    /**
     * 解析系统命令的绝对路径，避免被 PATH 中其他项目的同名命令遮蔽。
     *
     * @param list<string> $candidates
     */
    private function absoluteTool(array $candidates, string $fallback): string
    {
        foreach ($candidates as $candidate) {
            if (is_file($candidate) && is_executable($candidate)) {
                return $candidate;
            }
        }

        return $fallback;
    }

    /**
     * 移除本项目的快捷命令。
     *
     * @return array{files: list<string>, scripts: list<string>, errors: list<string>}
     */
    public function remove(bool $allowPrompt = true): array
    {
        $written = [];
        $errors = [];
        foreach ($this->homes(false) as $home) {
            foreach ($this->shellFiles($home) as $file) {
                if (!is_file($file) || !is_writable($file)) {
                    continue;
                }
                $content = @file_get_contents($file);
                if ($content === false) {
                    $errors[] = '读取失败：' . $file;
                    continue;
                }
                if (!$this->hasProjectBlock($content)) {
                    continue;
                }
                if ($this->hasUnclosedBlock($content)) {
                    $errors[] = '已有未闭合的项目命令块，请先手动处理：' . $file;
                    continue;
                }
                $stripped = rtrim($this->stripBlock($content), "\n");
                $new = $stripped === '' ? '' : $stripped . "\n";
                if (@file_put_contents($file, $new, LOCK_EX) === false) {
                    $errors[] = '写入失败：' . $file;
                    continue;
                }
                $written[] = $file;
            }
        }

        $removedScripts = [];
        if ($errors === []) {
            foreach ($this->findScripts() as $script) {
                if (@unlink($script['file'])) {
                    $removedScripts[] = $script['file'];
                } elseif ($this->sudoRemove($script['file'], $allowPrompt)) {
                    $removedScripts[] = $script['file'];
                } else {
                    $errors[] = '删除失败：' . $script['file'];
                }
            }
        }

        return ['files' => $written, 'scripts' => $removedScripts, 'errors' => $errors];
    }

    /**
     * 首次安装时的交互：给项目命令命名，15 秒无输入自动跳过。
     */
    public function promptInstall(int $timeout = self::PROMPT_TIMEOUT): int
    {
        if (!$this->isSupported() || $this->home === '') {
            return 0;
        }
        $existing = $this->find();
        $existingScripts = $this->findScripts();
        if ($existing !== [] || $existingScripts !== []) {
            $name = $existing[0]['name'] ?? $existingScripts[0]['name'];
            $where = $existing[0]['file'] ?? $existingScripts[0]['file'];
            fwrite(STDOUT, '项目快捷命令已设置：' . $name . '（' . $where . '）' . PHP_EOL);
            fwrite(STDOUT, '如需修改：php bin/w shell:alias --name=<新名字>；删除：php bin/w shell:alias --remove' . PHP_EOL);

            return 0;
        }
        if (!$this->isTty()) {
            fwrite(STDOUT, '提示：可运行 php bin/w shell:alias weline 设置项目快捷命令。' . PHP_EOL);

            return 0;
        }

        $name = $this->askName($timeout);
        if ($name === null) {
            return 0;
        }
        $result = $this->install($name);
        if ($result['errors'] !== []) {
            foreach ($result['errors'] as $error) {
                fwrite(STDERR, $error . PHP_EOL);
            }

            return 1;
        }
        $this->printInstalled($name, $result['files'], $result['script'], $result['warnings'], $result['system']);

        return 0;
    }

    public static function validateName(string $name): ?string
    {
        if ($name === '') {
            return '命令名不能为空。';
        }
        if (preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name) !== 1) {
            return '命令名只能包含字母、数字、下划线，且不能以数字开头（例如 weline、weline_cli）。';
        }
        $reserved = [
            'if', 'then', 'else', 'elif', 'fi', 'for', 'while', 'until', 'do', 'done',
            'case', 'esac', 'function', 'select', 'time', 'in', 'return', 'break',
            'continue', 'local', 'export', 'read', 'cd', 'alias', 'unalias', 'set',
            'unset', 'shift', 'source', 'eval', 'exec', 'exit',
        ];
        if (in_array(strtolower($name), $reserved, true)) {
            return '命令名不能使用 shell 保留字：' . $name;
        }

        return null;
    }

    private function askName(int $timeout): ?string
    {
        fwrite(STDOUT, PHP_EOL . '为项目快捷命令起个名字（例如 weline）：' . PHP_EOL);
        fwrite(STDOUT, '  之后在任意目录输入它，就会进入 ' . $this->root . ' 并执行 php bin/w。' . PHP_EOL);
        fwrite(STDOUT, '  示例：weline            → php bin/w' . PHP_EOL);
        fwrite(STDOUT, '        weline cache:clear → php bin/w cache:clear' . PHP_EOL);
        fwrite(STDOUT, '  直接回车或 ' . $timeout . ' 秒内不输入将跳过，稍后可运行 php bin/w shell:alias --name=<名字> 设置。' . PHP_EOL);
        fwrite(STDOUT, '命令名：');

        $read = [STDIN];
        $write = null;
        $except = null;
        $ready = @stream_select($read, $write, $except, $timeout);
        if (!$ready) {
            fwrite(STDOUT, PHP_EOL . '已跳过（' . $timeout . ' 秒无输入）。' . PHP_EOL);

            return null;
        }
        $line = fgets(STDIN);
        $name = is_string($line) ? trim($line) : '';
        if ($name === '') {
            fwrite(STDOUT, '已跳过。' . PHP_EOL);

            return null;
        }
        $error = self::validateName($name);
        if ($error !== null) {
            fwrite(STDERR, $error . PHP_EOL);
            fwrite(STDERR, '已跳过，稍后可重新运行 php bin/w shell:alias --name=<名字>。' . PHP_EOL);

            return null;
        }

        return $name;
    }

    /**
     * @param list<string> $files
     * @param list<string> $warnings
     */
    private function printInstalled(string $name, array $files, ?string $script, array $warnings, bool $system = false): void
    {
        fwrite(STDOUT, PHP_EOL . '✓ 项目快捷命令：' . $name . PHP_EOL);
        foreach ($files as $file) {
            fwrite(STDOUT, '  已写入：' . $file . PHP_EOL);
        }
        if ($script !== null) {
            fwrite(STDOUT, ($system ? '  已系统级安装（所有用户免 source 可用）：' : '  立即生效（当前用户免 source）：') . $script . PHP_EOL);
        } else {
            fwrite(STDOUT, '  当前终端需 source 或新终端后生效。' . PHP_EOL);
        }
        fwrite(STDOUT, '  用法：' . $name . '              # 进入项目并执行 php bin/w' . PHP_EOL);
        fwrite(STDOUT, '        ' . $name . ' cache:clear  # 等价于 php bin/w cache:clear' . PHP_EOL);
        fwrite(STDOUT, '  身份：项目用户自己直接执行；root 直接切换不询问密码；其他身份需输入项目用户本人的密码（Linux 走 su）。' . PHP_EOL);
        foreach ($warnings as $warning) {
            fwrite(STDOUT, '  提示：' . $warning . PHP_EOL);
        }
    }

    /**
     * 以项目用户身份执行 php bin/w 的子命令。
     *
     * `su - <用户> -c <脚本> 参数...` / `sudo -u <用户> sh -c <脚本> 参数...` 都会把后续参数
     * 交给目标用户的 shell（第一个参数成为 $0），所以统一按 _ <root> <home> <php> <args...> 取参数，
     * 由子命令自己 cd 到项目目录：调用者不一定是项目用户，可能根本进不去项目目录。
     */
    private function runnerScript(): string
    {
        return 'root="$1"; home="$2"; php="$3"; shift 3; cd "$root" || exit 1; exec env HOME="$home" "$php" bin/w "$@"';
    }

    private function renderBlock(string $name): string
    {
        $root = $this->quote($this->root);
        $php = $this->quote($this->phpBinary());
        $user = $this->quote($this->deployUser());
        $home = $this->quote($this->deployHome());
        $runner = $this->quote($this->runnerScript());
        $begin = self::BEGIN_PREFIX . ': ' . $this->root . ' >>>';

        return <<<SH
{$begin}
{$name}() {
    local _weline_root={$root}
    local _weline_php={$php}
    local _weline_user={$user}
    local _weline_home={$home}
    local _weline_runner={$runner}
    local _weline_status=0
    if [ ! -x "\$_weline_php" ]; then
        _weline_php="\$(command -v php)" || { echo '{$name}: 找不到 php 命令' >&2; return 127; }
    fi
    if [ "\$(id -un 2>/dev/null)" = "\$_weline_user" ]; then
        cd "\$_weline_root" || return 1
        env HOME="\$_weline_home" "\$_weline_php" bin/w "\$@"
        return \$?
    fi
    if [ "\$(id -u 2>/dev/null)" = 0 ]; then
        # root：直接切换为项目用户，不询问密码
        if command -v runuser >/dev/null 2>&1; then
            runuser -u "\$_weline_user" -- sh -c "\$_weline_runner" _ "\$_weline_root" "\$_weline_home" "\$_weline_php" "\$@"
        elif command -v sudo >/dev/null 2>&1; then
            sudo -u "\$_weline_user" -H sh -c "\$_weline_runner" _ "\$_weline_root" "\$_weline_home" "\$_weline_php" "\$@"
        elif command -v su >/dev/null 2>&1; then
            su - "\$_weline_user" -c "\$_weline_runner" _ "\$_weline_root" "\$_weline_home" "\$_weline_php" "\$@"
        else
            echo '{$name}: root 身份下没有 runuser / sudo / su，无法切换用户' >&2
            return 1
        fi
        _weline_status=\$?
    elif command -v sudo >/dev/null 2>&1 && sudo -n -u "\$_weline_user" -H true >/dev/null 2>&1; then
        # 当前身份已获免密切换授权：静默执行，不弹任何密码
        sudo -u "\$_weline_user" -H sh -c "\$_weline_runner" _ "\$_weline_root" "\$_weline_home" "\$_weline_php" "\$@"
        _weline_status=\$?
    elif [ "\$(uname -s 2>/dev/null)" = "Linux" ] && command -v su >/dev/null 2>&1; then
        # 普通身份：切换到项目用户需要项目用户本人的密码
        echo "{$name}: 正在切换到 \${_weline_user}，请输入 \${_weline_user} 的密码" >&2
        su - "\$_weline_user" -c "\$_weline_runner" _ "\$_weline_root" "\$_weline_home" "\$_weline_php" "\$@"
        _weline_status=\$?
    elif command -v sudo >/dev/null 2>&1; then
        # 兜底：sudo（需要当前身份自己的 sudo 密码 / 管理员权限）
        echo "{$name}: 本机 su 不可用，改用 sudo 切换到 \${_weline_user}，请输入当前身份的 sudo 密码" >&2
        sudo -u "\$_weline_user" -H sh -c "\$_weline_runner" _ "\$_weline_root" "\$_weline_home" "\$_weline_php" "\$@"
        _weline_status=\$?
    else
        echo "{$name}: 无法切换到 \${_weline_user}：本机没有 su 与 sudo，请联系管理员给 \${_weline_user} 设置密码" >&2
        _weline_status=1
    fi
    cd "\$_weline_root" 2>/dev/null || true
    return \$_weline_status
}
# <<< Weline project command <<<
SH;
    }

    private function renderScript(string $name): string
    {
        $rootLit = $this->quote($this->root);
        $php = $this->quote($this->phpBinary());
        $user = $this->quote($this->deployUser());
        $home = $this->quote($this->deployHome());
        $runner = $this->quote($this->runnerScript());
        $marker = $this->scriptMarker();

        return <<<SH
#!/usr/bin/env bash
{$marker}
NAME={$name}
ROOT={$rootLit}
PHP={$php}
DEPLOY_USER={$user}
DEPLOY_HOME={$home}
RUNNER={$runner}

if [[ ! -x "\$PHP" ]]; then
  PHP="\$(command -v php)" || { printf '%s\\n' "\$NAME: 找不到 php 命令" >&2; exit 127; }
fi

if [[ "\$(id -un 2>/dev/null)" == "\$DEPLOY_USER" ]]; then
  cd "\$ROOT" || exit 1
  exec env HOME="\$DEPLOY_HOME" "\$PHP" bin/w "\$@"
fi

if [[ "\$(id -u 2>/dev/null)" == 0 ]]; then
  # root：直接切换为项目用户，不询问密码
  if command -v runuser >/dev/null 2>&1; then
    exec runuser -u "\$DEPLOY_USER" -- sh -c "\$RUNNER" _ "\$ROOT" "\$DEPLOY_HOME" "\$PHP" "\$@"
  fi
  if command -v sudo >/dev/null 2>&1; then
    exec sudo -u "\$DEPLOY_USER" -H sh -c "\$RUNNER" _ "\$ROOT" "\$DEPLOY_HOME" "\$PHP" "\$@"
  fi
  if command -v su >/dev/null 2>&1; then
    exec su - "\$DEPLOY_USER" -c "\$RUNNER" _ "\$ROOT" "\$DEPLOY_HOME" "\$PHP" "\$@"
  fi
  printf '%s\\n' "\$NAME: root 身份下没有 runuser / sudo / su，无法切换用户" >&2
  exit 1
fi

if command -v sudo >/dev/null 2>&1 && sudo -n -u "\$DEPLOY_USER" -H true >/dev/null 2>&1; then
  # 当前身份已获免密切换授权：静默执行
  exec sudo -u "\$DEPLOY_USER" -H sh -c "\$RUNNER" _ "\$ROOT" "\$DEPLOY_HOME" "\$PHP" "\$@"
fi

if [[ "\$(uname -s 2>/dev/null)" == "Linux" ]] && command -v su >/dev/null 2>&1; then
  # 普通身份：切换到项目用户需要项目用户本人的密码
  printf '%s\\n' "\$NAME: 正在切换到 \${DEPLOY_USER}，请输入 \${DEPLOY_USER} 的密码" >&2
  su - "\$DEPLOY_USER" -c "\$RUNNER" _ "\$ROOT" "\$DEPLOY_HOME" "\$PHP" "\$@"
  exit \$?
fi

if command -v sudo >/dev/null 2>&1; then
  # 兜底：sudo（需要当前身份自己的 sudo 密码 / 管理员权限）
  printf '%s\\n' "\$NAME: 本机 su 不可用，改用 sudo 切换到 \${DEPLOY_USER}，请输入当前身份的 sudo 密码" >&2
  exec sudo -u "\$DEPLOY_USER" -H sh -c "\$RUNNER" _ "\$ROOT" "\$DEPLOY_HOME" "\$PHP" "\$@"
fi

printf '%s\\n' "\$NAME: 无法切换到 \${DEPLOY_USER}：本机没有 su 与 sudo，请联系管理员给 \${DEPLOY_USER} 设置密码" >&2
exit 1
SH;
    }

    private function scriptMarker(): string
    {
        return self::SCRIPT_PREFIX . $this->root . self::SCRIPT_SUFFIX;
    }

    private function readName(string $file): ?string
    {
        $lines = @file($file, FILE_IGNORE_NEW_LINES);
        if (!is_array($lines)) {
            return null;
        }
        $inside = false;
        foreach ($lines as $line) {
            if (!$inside) {
                if ($this->isProjectBegin($line)) {
                    $inside = true;
                }
                continue;
            }
            if (trim($line) === self::END_MARKER) {
                break;
            }
            if (preg_match('/^([A-Za-z_][A-Za-z0-9_]*)\s*\(\)/', trim($line), $matches) === 1) {
                return $matches[1];
            }
        }

        return null;
    }

    private function hasProjectBlock(string $content): bool
    {
        foreach ($this->lines($content) as $line) {
            if ($this->isProjectBegin($line)) {
                return true;
            }
        }

        return false;
    }

    private function hasUnclosedBlock(string $content): bool
    {
        $inside = false;
        foreach ($this->lines($content) as $line) {
            if (!$inside) {
                if ($this->isAnyProjectBegin($line)) {
                    $inside = true;
                }
                continue;
            }
            if (trim($line) === self::END_MARKER) {
                $inside = false;
            }
        }

        return $inside;
    }

    /**
     * 移除项目命令块：本项目的旧块全部移除；同名块（项目换路径后的遗留）也移除。
     */
    private function stripBlock(string $content, ?string $name = null): string
    {
        $kept = [];
        $block = [];
        $inside = false;
        foreach ($this->lines($content) as $line) {
            if (!$inside) {
                if ($this->isAnyProjectBegin($line)) {
                    $inside = true;
                    $block = [$line];
                    continue;
                }
                $kept[] = $line;
                continue;
            }
            $block[] = $line;
            if (trim($line) !== self::END_MARKER) {
                continue;
            }
            $inside = false;
            if (!$this->isProjectBegin($block[0])
                && ($name === null || $this->blockName($block) !== $name)
            ) {
                array_push($kept, ...$block);
            }
            $block = [];
        }
        if ($inside) {
            array_push($kept, ...$block);
        }

        return implode("\n", $kept);
    }

    private function isAnyProjectBegin(string $line): bool
    {
        return str_starts_with($line, self::BEGIN_PREFIX);
    }

    /**
     * @param list<string> $block
     */
    private function blockName(array $block): ?string
    {
        foreach ($block as $line) {
            if (preg_match('/^([A-Za-z_][A-Za-z0-9_]*)\s*\(\)/', trim($line), $matches) === 1) {
                return $matches[1];
            }
        }

        return null;
    }

    private function isProjectBegin(string $line): bool
    {
        return str_starts_with($line, self::BEGIN_PREFIX)
            && str_contains($line, $this->root);
    }

    /**
     * @return list<string>
     */
    private function lines(string $content): array
    {
        $lines = preg_split('/\R/', $content);

        return is_array($lines) ? $lines : [];
    }

    private function phpBinary(): string
    {
        $projectPhp = $this->root . DIRECTORY_SEPARATOR . 'extend' . DIRECTORY_SEPARATOR
            . 'server' . DIRECTORY_SEPARATOR . 'php' . DIRECTORY_SEPARATOR . 'bin' . DIRECTORY_SEPARATOR . 'php';
        if (is_file($projectPhp) && is_executable($projectPhp)) {
            return $projectPhp;
        }

        return (\PHP_BINARY !== '' && is_file(\PHP_BINARY)) ? \PHP_BINARY : 'php';
    }

    private function deployUser(): string
    {
        $user = '';
        try {
            $user = (string)Env::get('user');
        } catch (\Throwable) {
            $user = '';
        }
        if ($user === '' && function_exists('posix_getpwuid') && function_exists('posix_geteuid')) {
            $info = posix_getpwuid(posix_geteuid());
            $user = is_array($info) ? (string)($info['name'] ?? '') : '';
        }
        if ($user === '') {
            $user = (string)(getenv('USER') ?: get_current_user());
        }

        return $user;
    }

    /**
     * 以项目用户执行时使用的 HOME（与 sudo -H 等价，避免读错配置目录）。
     */
    private function deployHome(): string
    {
        $home = $this->userHome($this->deployUser());

        return $home !== '' ? $home : $this->home;
    }

    /**
     * 当前 PHP 进程的运行用户（与 shell 里的登录用户可能不同，例如 sudo -u）。
     */
    private function currentUser(): string
    {
        if (function_exists('posix_getpwuid') && function_exists('posix_geteuid')) {
            $info = posix_getpwuid(posix_geteuid());
            if (is_array($info) && !empty($info['name'])) {
                return (string)$info['name'];
            }
        }

        return (string)(getenv('USER') ?: get_current_user());
    }

    private function userHome(string $user): string
    {
        if ($user !== '' && function_exists('posix_getpwnam')) {
            $info = posix_getpwnam($user);
            if (is_array($info) && !empty($info['dir'])) {
                return rtrim((string)$info['dir'], '/\\');
            }
        }

        return $user === 'root' ? '/root' : '';
    }

    private function quote(string $value): string
    {
        return "'" . str_replace("'", "'\\''", $value) . "'";
    }

    private function isTty(): bool
    {
        if (function_exists('stream_isatty')) {
            return @stream_isatty(STDIN);
        }
        if (function_exists('posix_isatty')) {
            return @posix_isatty(STDIN);
        }

        return false;
    }
