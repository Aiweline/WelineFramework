<?php

declare(strict_types=1);

namespace Weline\Seo\Service\Protocol;

use Weline\Framework\App\Env;
use Weline\Framework\DataObject\DataObject;
use Weline\Framework\Event\EventsManager;
use Weline\Framework\Manager\ObjectManager;
use Weline\Seo\Model\WebsiteProtocolConfig;

class RobotsTxtRenderer
{
    public function __construct(
        private readonly WebsiteProtocolResolver $websiteResolver,
        private readonly WebsiteProtocolConfig $protocolConfig,
        private readonly \Weline\Seo\Service\StoreModeSeoHardGate $storeModeGate = new \Weline\Seo\Service\StoreModeSeoHardGate(),
        private readonly ?EventsManager $eventsManager = null,
    ) {
    }

    public function render(): string
    {
        if ($this->storeModeGate->isHardNoIndexMode()) {
            return $this->storeModeGate->forceRobotsTxt();
        }

        $website = $this->websiteResolver->currentWebsite();
        $websiteId = (int)($website['website_id'] ?? 0);
        $config = $this->loadWebsiteConfig($websiteId);
        $baseUrl = rtrim((string)($website['url'] ?? $this->websiteResolver->currentBaseUrl()), '/');
        $contribution = $this->robotContributions($baseUrl, $websiteId, $config->isRobotsEnabled());
        $lines = ['# Generated by Weline_Seo'];
        foreach ($contribution['global_lines'] as $line) {
            $lines[] = $line;
        }
        $lines[] = 'User-agent: *';
        foreach ($contribution['star_lines'] as $line) {
            $lines[] = $line;
        }

        if ($config->isRobotsEnabled()) {
            $lines[] = 'Allow: /';
            foreach ($this->defaultDisallowPaths() as $path) {
                $lines[] = 'Disallow: ' . $path;
            }
            foreach ($this->extraDirectives($config->getRobotsExtra()) as $directive) {
                $lines[] = $directive;
            }
        } else {
            $lines[] = 'Disallow: /';
        }

        if ($this->shouldDisallowGoogleExtended($config)) {
            $lines[] = '';
            $lines[] = 'User-agent: Google-Extended';
            $lines[] = 'Disallow: /';
        }

        if ($config->isSitemapEnabled()) {
            $sitemapUrls = $this->sitemapDeclarationUrls($website);
            if ($sitemapUrls !== []) {
                $lines[] = '';
                foreach ($sitemapUrls as $sitemapUrl) {
                    $lines[] = 'Sitemap: ' . $sitemapUrl;
                }
            }
        }

        return implode("\n", $lines) . "\n";
    }

    /**
     * @return array{global_lines: list<string>, star_lines: list<string>}
     */
    private function robotContributions(string $baseUrl, int $websiteId, bool $robotsEnabled): array
    {
        $bag = new DataObject([
            'global_lines' => [],
            'star_lines' => [],
            'base_url' => $baseUrl,
            'website_id' => $websiteId,
            'robots_enabled' => $robotsEnabled,
        ]);

        $events = $this->eventsManager ?? ObjectManager::getInstance(EventsManager::class);
        $events->dispatch('Weline_Seo::protocol::robots_contribute', $bag);

        return [
            'global_lines' => $this->sanitizeDirectiveLines($bag->getData('global_lines')),
            'star_lines' => $this->sanitizeDirectiveLines($bag->getData('star_lines')),
        ];
    }

    /**
     * @return list<string>
     */
    private function sanitizeDirectiveLines(mixed $lines): array
    {
        if (!is_array($lines)) {
            return [];
        }

        $clean = [];
        foreach ($lines as $line) {
            if (!is_string($line)) {
                continue;
            }
            $line = str_replace(["\r", "\n"], '', trim($line));
            if ($line === '' || strlen($line) > 500) {
                continue;
            }
            $clean[] = $line;
        }

        return $clean;
    }

    /**
     * Declare the generated canonical sitemap, preserving its port and base path.
     *
     * @param array<string, mixed> $website
     * @return list<string>
     */
    private function sitemapDeclarationUrls(array $website): array
    {
        $baseUrl = rtrim((string)($website['url'] ?? $this->websiteResolver->currentBaseUrl()), '/');
        return $baseUrl !== '' ? [$baseUrl . '/sitemap.xml'] : [];
    }

    /**
     * @return string[]
     */
    private function defaultDisallowPaths(): array
    {
        $paths = [
            '/rest/',
            '/backend/',
            '/location/rest/',
        ];

        $backendPrefix = (string)Env::getAreaRoutePrefix('backend');
        if ($backendPrefix !== '') {
            $paths[] = '/' . trim($backendPrefix, '/') . '/';
        }

        return array_values(array_unique(array_filter($paths)));
    }

    private function shouldDisallowGoogleExtended(WebsiteProtocolConfig $config): bool
    {
        if ($config->getGoogleExtendedPolicy() === 'disallow') {
            return true;
        }

        $value = strtolower((string)w_env('seo.robots.google_extended', 'allow'));
        return in_array($value, ['disallow', 'deny', 'block', '0', 'false'], true);
    }

    private function loadWebsiteConfig(int $websiteId): WebsiteProtocolConfig
    {
        try {
            if ($websiteId >= 0) {
                return $this->protocolConfig->loadByWebsiteId($websiteId);
            }
        } catch (\Throwable) {
        }

        return $this->protocolConfig->reset();
    }

    /**
     * @return string[]
     */
    private function extraDirectives(string $value): array
    {
        $lines = preg_split('/\r\n|\r|\n/', $value) ?: [];
        $directives = [];
        foreach ($lines as $line) {
            $line = trim((string)$line);
            if ($line === '') {
                continue;
            }
            $directives[] = str_replace(["\r", "\n"], '', $line);
        }

        return $directives;
    }
}
