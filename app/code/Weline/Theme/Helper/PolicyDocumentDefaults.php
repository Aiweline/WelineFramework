/**
 * Default copy for policy-document widget (Chinese source strings).
 * Empty widget config falls back here so storefront matches pre-widget Theme layouts.
 *
 * Editor must also hydrate empty sections/links into data-config — render-only
 * fallback leaves the ParamSchema array at 0 items so merchants cannot edit.
 */
final class PolicyDocumentDefaults
{
    /** @return array<string,mixed> */
    public static function forPage(string $page): array
    {
        $page = trim($page);
        // /terms layout shares the same default copy as policy/term-condition.
        if ($page === 'terms') {
            $page = 'term-condition';
        }
        $all = self::all();
        if (isset($all[$page])) {
            return $all[$page];
        }
        return $all['privacy'] ?? [
            'variant' => 'amazon',
            'title' => '政策',
            'lead' => '',
            'intro' => '',
            'footer_note' => '',
            'show_legal_contact' => false,
            'related_links' => [],
            'sections' => [],
        ];
    }

    /**
     * Fill empty editor/runtime params from catalog defaults for the given page key.
     * Empty sections/related_links means “not extracted yet”, not an intentional blank page.
     *
     * @param array<string,mixed> $params
     * @return array<string,mixed>
     */
    public static function hydrateParams(array $params): array
    {
        $page = trim((string)($params['page'] ?? 'privacy'));
        if ($page === '') {
            $page = 'privacy';
        }
        $params['page'] = $page;
        $defaults = self::forPage($page);

        $sectionsWereEmpty = !\is_array($params['sections'] ?? null) || $params['sections'] === [];
        $linksWereEmpty = !\is_array($params['related_links'] ?? null) || $params['related_links'] === [];

        foreach (['title', 'lead', 'intro', 'footer_note', 'updated_at', 'toc_aria', 'article_aria', 'variant'] as $key) {
            $cur = $params[$key] ?? null;
            if ($cur !== null && $cur !== '') {
                continue;
            }
            if (!\array_key_exists($key, $defaults)) {
                continue;
            }
            $fallback = $defaults[$key];
            if ($fallback === null || $fallback === '') {
                if ($key === 'variant') {
                    $params[$key] = 'amazon';
                }
                continue;
            }
            $params[$key] = $fallback;
        }

        if ($sectionsWereEmpty) {
            $params['sections'] = \array_values(\array_filter(
                \is_array($defaults['sections'] ?? null) ? $defaults['sections'] : [],
                'is_array'
            ));
            // Registry default show_legal_contact=false would otherwise mask page-level true.
            $params['show_legal_contact'] = (bool)($defaults['show_legal_contact'] ?? false);
        }

        if ($linksWereEmpty) {
            $params['related_links'] = \array_values(\array_filter(
                \is_array($defaults['related_links'] ?? null) ? $defaults['related_links'] : [],
                'is_array'
            ));
        }

        return $params;
    }

