<?php

declare(strict_types=1);

namespace Weline\Server\Service\Edge\Nginx;

use Weline\Framework\Compilation\CompiledPhpRegistry;

/**
 * β edge pairing for FPC Extra query_keys allowlist.
 *
 * Reads the same compiled Framework snapshot as Coordinator
 * (`generated/framework/fpc_policy_snapshot.php`) and publishes an Nginx map:
 * path∈configured patterns ∧ request contains an allowlisted query key
 * → `$wls_fpc_html_query_allowlist_bypass=1` (OR'd into html-disk bypass).
 *
 * Peer field contract (Framework):
 * - schema_version = fpc-policy-snapshot.v1
 * - declarations[*].attrs.enabled : bool
 * - declarations[*].attrs.query_keys : list<string> (lowercase, explicit; no `*`)
 * - declarations[*].path_pattern / public_path_patterns : storefront paths
 *
 * Does NOT hardcode business query names. Empty/missing query_keys → path-only
 * (map default 0). Never emits ~q/{sha1} disk leaves (α forbidden).
 */
final class FpcQueryAllowlistNginxMapWriter
{
    public const MAP_BASENAME = 'fpc-query-allowlist.map.conf';

    public const SNAPSHOT_RELATIVE = '/generated/framework/fpc_policy_snapshot.php';

    public const SNAPSHOT_SCHEMA = 'fpc-policy-snapshot.v1';

    /**
     * Optional lang/currency segments before policy path.
     * Must NOT match plain storefront segments like /products (no underscore, len>2).
     * Matches: /en, /zh_Hans_CN, /USD — not /products or /categories.
     */
    private const LOC_PREFIX = '(?:/(?:[A-Za-z]{2}(?:_[A-Za-z0-9]+)+|[A-Za-z]{2}|[A-Z]{3})){0,4}';

    public const MAX_RULES = 512;

    public function __construct(
        private readonly ManagedNginxPaths $paths = new ManagedNginxPaths(),
    ) {
    }

    public function mapFilePath(): string
    {
        return $this->paths->confDir() . \DIRECTORY_SEPARATOR . self::MAP_BASENAME;
    }

    /**
     * @param array<string, mixed>|null $snapshot null → load compiled Framework snapshot
     * @return array{ok:bool, path:string, message:string, rule_count:int}
     */
    public function publish(?array $snapshot = null): array
    {
        $this->paths->ensureRuntimeDirectories();
        $path = $this->mapFilePath();
        $dir = \dirname($path);
        if (!\is_dir($dir) && !@\mkdir($dir, 0775, true) && !\is_dir($dir)) {
            return [
                'ok' => false,
                'path' => $path,
                'message' => 'conf_dir_unavailable',
                'rule_count' => 0,
            ];
        }

        $snapshot ??= $this->loadSnapshot();
        $body = $this->buildMapBody($snapshot);
        $ruleCount = \preg_match_all('/^\s+"~[^"]+"\s+1;\s*$/m', $body) ?: 0;

        $previous = \is_file($path) ? (string)@\file_get_contents($path) : null;
        $tmp = $dir . \DIRECTORY_SEPARATOR . '.tmp-fpc-qa-' . \bin2hex(\random_bytes(6));
        if (@\file_put_contents($tmp, $body, \LOCK_EX) === false) {
            @\unlink($tmp);

            return [
                'ok' => false,
                'path' => $path,
                'message' => 'temp_write_failed',
                'rule_count' => 0,
            ];
        }
        if (!@\rename($tmp, $path)) {
            @\unlink($tmp);
            if (\is_string($previous)) {
                @\file_put_contents($path, $previous, \LOCK_EX);
            }

            return [
                'ok' => false,
                'path' => $path,
                'message' => 'publish_rename_failed',
                'rule_count' => 0,
            ];
        }
        @\chmod($path, 0644);

        return [
            'ok' => true,
            'path' => $path,
            'message' => 'published',
            'rule_count' => $ruleCount,
        ];
    }

    /**
     * @param array<string, mixed> $snapshot
     */
    public function buildMapBody(array $snapshot): string
    {
        $rules = self::extractRules($snapshot);
        $lines = [
            '# Generated by FpcQueryAllowlistNginxMapWriter — do not hand-edit.',
            '# Source: generated/framework/fpc_policy_snapshot.php (attrs.query_keys).',
            '# β: allowlisted query on configured path → bypass html-disk (Shared HIT).',
            'map $request_uri $wls_fpc_html_query_allowlist_bypass {',
            '    default 0;',
        ];
        foreach ($rules as $rule) {
            $regex = $this->requestUriRegex($rule['path_pattern'], $rule['query_key']);
            if ($regex === null) {
                continue;
            }
            $lines[] = '    "' . $regex . '" 1;';
        }
        $lines[] = '}';
        $lines[] = '';

        return \implode("\n", $lines);
    }

    /**
     * @param array<string, mixed> $snapshot
     * @return list<array{path_pattern:string, query_key:string}>
     */
    public static function extractRules(array $snapshot): array
    {
        if (($snapshot['schema_version'] ?? '') !== self::SNAPSHOT_SCHEMA) {
            return [];
        }
        $out = [];
        $seen = [];
        foreach ((array)($snapshot['declarations'] ?? []) as $row) {
            if (!\is_array($row)) {
                continue;
            }
            if (($row['type'] ?? 'fpc') !== 'fpc') {
                continue;
            }
            $attrs = \is_array($row['attrs'] ?? null) ? $row['attrs'] : [];
            if (\array_key_exists('enabled', $attrs) && !(bool)$attrs['enabled']) {
                continue;
            }
            $keys = self::normalizeQueryKeys($attrs['query_keys'] ?? null);
            if ($keys === []) {
                continue;
            }
            $paths = [];
            foreach ([(string)($row['path_pattern'] ?? ''), ...(array)($row['public_path_patterns'] ?? [])] as $pattern) {
                $pattern = self::normalizePathPattern((string)$pattern);
                if ($pattern === '') {
                    continue;
                }
                $paths[$pattern] = true;
            }
            foreach (\array_keys($paths) as $pattern) {
                foreach ($keys as $key) {
                    $pair = $pattern . "\0" . $key;
                    if (isset($seen[$pair])) {
                        continue;
                    }
                    $seen[$pair] = true;
                    $out[] = ['path_pattern' => $pattern, 'query_key' => $key];
                    if (\count($out) >= self::MAX_RULES) {
                        return $out;
                    }
                }
            }
        }

        return $out;
    }

    /**
     * @return list<string>
     */
    public static function normalizeQueryKeys(mixed $raw): array
    {
        if ($raw === null || $raw === '') {
            return [];
        }
        if (\is_string($raw)) {
            $raw = \explode(',', $raw);
        }
        if (!\is_array($raw)) {
            return [];
        }
        $keys = [];
        foreach ($raw as $item) {
            $key = \strtolower(\trim((string)$item));
            if ($key === '' || $key === '*') {
                // fail-closed: wildcard / empty never becomes an edge rule
                continue;
            }
            if (\preg_match('/^[a-z][a-z0-9_]{0,63}$/', $key) !== 1) {
                continue;
            }
            $keys[$key] = true;
        }

        return \array_keys($keys);
    }

    public static function normalizePathPattern(string $pattern): string
    {
        $pattern = \trim($pattern);
        if ($pattern === '' || \str_contains($pattern, '?') || \str_contains($pattern, '#')) {
            return '';
        }
        if ($pattern[0] !== '/') {
            $pattern = '/' . $pattern;
        }
        // Reject path traversal / NUL in patterns from snapshot.
        if (\str_contains($pattern, '..') || \str_contains($pattern, "\0")) {
            return '';
        }

        return $pattern;
    }

    /**
     * @return array<string, mixed>
     */
    public function loadSnapshot(): array
    {
        $root = $this->paths->projectRoot();
        if ($root === '' && \defined('BP')) {
            $root = (string)BP;
        }
        $path = \rtrim($root, '\\/') . self::SNAPSHOT_RELATIVE;
        if (!\is_file($path)) {
            return [];
        }
        try {
            $data = CompiledPhpRegistry::load($path);
        } catch (\Throwable) {
            $data = @include $path;
        }
        if (!\is_array($data)) {
            return [];
        }

        return $data;
    }

    private function requestUriRegex(string $pathPattern, string $queryKey): ?string
    {
        $pathPattern = self::normalizePathPattern($pathPattern);
        $keys = self::normalizeQueryKeys([$queryKey]);
        if ($pathPattern === '' || $keys === []) {
            return null;
        }
        $queryKey = $keys[0];
        // Quote then restore * / ** wildcards used by Extra public_path_patterns.
        $quoted = \preg_quote($pathPattern, '#');
        $pathRe = \str_replace(['\\*\\*', '\\*'], ['[^?]*', '[^/?]+'], $quoted);
        // LOC + path + optional slash + ? + optional other args + key=
        // Example: /en_US/USD/products?utm=1&price=100 → HIT; /products → MISS.
        return '~*^' . self::LOC_PREFIX . $pathRe . '(?:/)?\?(?:.*&)?' . \preg_quote($queryKey, '#') . '=';
    }
}
