<?php

declare(strict_types=1);

namespace Weline\Server\Service\Edge\Nginx;

/**
 * Atomically publishes managed-Nginx map + location snippets that disk-serve
 * published sitemap XML under pub/sitemaps/{website_code}/…
 *
 * Spec shape (from Seo coordinator):
 * - default_website_code:string
 * - host_to_code: array<string,string>  host (lowercase, no port) => website_code
 * - index_locations: list<{path:string, website_code:string}>
 *   exact request paths for sitemap indexes (e.g. /sitemap.xml, /shop/sitemap.xml)
 */
final class SitemapEdgeNginxMapWriter
{
    public const MAP_BASENAME = 'sitemap-edge.map.conf';
    public const LOCATIONS_BASENAME = 'sitemap-edge.locations.conf';

    public function __construct(
        private readonly ManagedNginxPaths $paths = new ManagedNginxPaths(),
    ) {
    }

    public function mapFilePath(): string
    {
        return $this->paths->confDir() . \DIRECTORY_SEPARATOR . self::MAP_BASENAME;
    }

    public function locationsFilePath(): string
    {
        return $this->paths->confDir() . \DIRECTORY_SEPARATOR . self::LOCATIONS_BASENAME;
    }

    /**
     * @param array{
     *   default_website_code?:string,
     *   host_to_code?:array<string,string>,
     *   index_locations?:list<array{path:string,website_code:string}>
     * } $spec
     * @return array{ok:bool, map_path:string, locations_path:string, message:string}
     */
    public function publish(array $spec = []): array
    {
        $this->paths->ensureRuntimeDirectories();
        $pubRoot = $this->paths->projectRoot() . \DIRECTORY_SEPARATOR . 'pub';
        $quotedPubRoot = $this->quotePath($pubRoot);
        $defaultCode = $this->safeCode((string)($spec['default_website_code'] ?? 'default'), 'default');
        $hostToCode = [];
        foreach ((array)($spec['host_to_code'] ?? []) as $host => $code) {
            $host = \strtolower(\trim((string)$host));
            $code = $this->safeCode((string)$code, '');
            if ($host === '' || $code === '' || \str_contains($host, '/') || \str_contains($host, '\\')) {
                continue;
            }
            $hostToCode[$host] = $code;
        }
        if ($hostToCode === []) {
            $hostToCode['localhost'] = $defaultCode;
        }

        $indexLocations = [];
        foreach ((array)($spec['index_locations'] ?? []) as $row) {
            if (!\is_array($row)) {
                continue;
            }
            $path = $this->normalizeIndexPath((string)($row['path'] ?? ''));
            $code = $this->safeCode((string)($row['website_code'] ?? ''), '');
            if ($path === '' || $code === '') {
                continue;
            }
            $indexLocations[$path] = $code;
        }
        if ($indexLocations === []) {
            $indexLocations['/sitemap.xml'] = $defaultCode;
        }

        $mapLines = [
            '# Generated by SitemapEdgeNginxMapWriter — do not hand-edit.',
            'map $host $wls_sitemap_website_code {',
            '    default "' . $this->escapeNginxString($defaultCode) . '";',
        ];
        foreach ($hostToCode as $host => $code) {
            $mapLines[] = '    "' . $this->escapeNginxString($host) . '" "'
                . $this->escapeNginxString($code) . '";';
        }
        $mapLines[] = '}';
        $mapLines[] = '';

        $locLines = [
            '# Generated by SitemapEdgeNginxMapWriter — do not hand-edit.',
            '# Sitemap shards: URL path == pub-relative path.',
            'location ^~ /sitemaps/ {',
            '    root ' . $quotedPubRoot . ';',
            '    default_type application/xml;',
            '    charset utf-8;',
            '    access_log off;',
            '    add_header Cache-Control "public, max-age=300, must-revalidate" always;',
            '    add_header X-Wls-Sitemap-Disk "1" always;',
            '    try_files $uri =404;',
            '}',
            '',
            // Root index: Host → website_code via map (http context).
            'location = /sitemap.xml {',
            '    root ' . $quotedPubRoot . ';',
            '    default_type application/xml;',
            '    charset utf-8;',
            '    access_log off;',
            '    add_header Cache-Control "public, max-age=300, must-revalidate" always;',
            '    add_header X-Wls-Sitemap-Disk "1" always;',
            '    try_files /sitemaps/$wls_sitemap_website_code/canonical/sitemap.xml =404;',
            '}',
            '',
        ];
        foreach ($indexLocations as $path => $code) {
            if ($path === '/sitemap.xml') {
                continue; // handled by Host map above
            }
            $rel = '/sitemaps/' . $code . '/canonical/sitemap.xml';
            $locLines[] = 'location = ' . $path . ' {';
            $locLines[] = '    root ' . $quotedPubRoot . ';';
            $locLines[] = '    default_type application/xml;';
            $locLines[] = '    charset utf-8;';
            $locLines[] = '    access_log off;';
            $locLines[] = '    add_header Cache-Control "public, max-age=300, must-revalidate" always;';
            $locLines[] = '    add_header X-Wls-Sitemap-Disk "1" always;';
            $locLines[] = '    try_files ' . $rel . ' =404;';
            $locLines[] = '}';
            $locLines[] = '';
        }

        $mapBody = \implode("\n", $mapLines);
        $locBody = \implode("\n", $locLines);
        $mapOk = $this->atomicWrite($this->mapFilePath(), $mapBody);
        if (!$mapOk['ok']) {
            return [
                'ok' => false,
                'map_path' => $this->mapFilePath(),
                'locations_path' => $this->locationsFilePath(),
                'message' => $mapOk['message'],
            ];
        }
        $locOk = $this->atomicWrite($this->locationsFilePath(), $locBody);
        if (!$locOk['ok']) {
            return [
                'ok' => false,
                'map_path' => $this->mapFilePath(),
                'locations_path' => $this->locationsFilePath(),
                'message' => $locOk['message'],
            ];
        }

        return [
            'ok' => true,
            'map_path' => $this->mapFilePath(),
            'locations_path' => $this->locationsFilePath(),
            'message' => 'published',
        ];
    }

    /**
     * Publish empty-safe defaults so nginx -t never fails on missing include.
     *
     * @return array{ok:bool, map_path:string, locations_path:string, message:string}
     */
    public function publishDefaults(): array
    {
        return $this->publish([
            'default_website_code' => 'default',
            'host_to_code' => [],
            'index_locations' => [
                ['path' => '/sitemap.xml', 'website_code' => 'default'],
            ],
        ]);
    }

    /**
     * @return array{ok:bool, message:string}
     */
    private function atomicWrite(string $path, string $body): array
    {
        $dir = \dirname($path);
        if (!\is_dir($dir) && !@\mkdir($dir, 0775, true) && !\is_dir($dir)) {
            return ['ok' => false, 'message' => 'conf_dir_unavailable'];
        }
        $previous = \is_file($path) ? (string)@\file_get_contents($path) : null;
        $tmp = $dir . \DIRECTORY_SEPARATOR . '.tmp-sitemap-edge-' . \bin2hex(\random_bytes(6));
        if (@\file_put_contents($tmp, $body, \LOCK_EX) === false) {
            @\unlink($tmp);

            return ['ok' => false, 'message' => 'temp_write_failed'];
        }
        if (!@\rename($tmp, $path)) {
            @\unlink($tmp);
            if (\is_string($previous)) {
                @\file_put_contents($path, $previous, \LOCK_EX);
            }

            return ['ok' => false, 'message' => 'publish_rename_failed'];
        }
        @\chmod($path, 0600);

        return ['ok' => true, 'message' => 'published'];
    }

    private function quotePath(string $path): string
    {
        $normalized = \str_replace('\\', '/', $path);

        return '"' . \str_replace('"', '\\"', $normalized) . '"';
    }

    private function escapeNginxString(string $value): string
    {
        return \str_replace(['\\', '"'], ['\\\\', '\\"'], $value);
    }

    private function safeCode(string $code, string $fallback): string
    {
        $code = \trim($code);
        if ($code === '' || \preg_match('/^[A-Za-z0-9_-]+$/D', $code) !== 1) {
            return $fallback;
        }

        return $code;
    }

    private function normalizeIndexPath(string $path): string
    {
        $path = \strtolower(\trim(\str_replace('\\', '/', $path)));
        if ($path === '') {
            return '';
        }
        if ($path[0] !== '/') {
            $path = '/' . $path;
        }
        if (\preg_match('#^/[A-Za-z0-9/_-]*sitemap\\.xml$#D', $path) !== 1) {
            return '';
        }

        return $path;
    }
}
