<?php

declare(strict_types=1);

namespace Weline\Server\Service\Edge\Nginx;

use Weline\Framework\Http\Fpc\FpcPierceStamp;

/**
 * Atomically publishes the managed Nginx map snippet that recognizes the
 * current FPC pierce stamp (cookie + query).
 */
final class FpcPierceNginxMapWriter
{
    public const MAP_BASENAME = 'fpc-pierce.map.conf';

    public function __construct(
        private readonly ManagedNginxPaths $paths = new ManagedNginxPaths(),
    ) {
    }

    public function mapFilePath(): string
    {
        return $this->paths->confDir() . \DIRECTORY_SEPARATOR . self::MAP_BASENAME;
    }

    /**
     * @return array{ok:bool, path:string, message:string}
     */
    public function publish(?string $secret = null): array
    {
        $secret = \strtolower(\trim((string)($secret ?? FpcPierceStamp::ensureSecret())));
        if ($secret === '' || !\ctype_xdigit($secret)) {
            return [
                'ok' => false,
                'path' => $this->mapFilePath(),
                'message' => 'invalid_pierce_secret',
            ];
        }
        $this->paths->ensureRuntimeDirectories();
        $path = $this->mapFilePath();
        $dir = \dirname($path);
        if (!\is_dir($dir) && !@\mkdir($dir, 0775, true) && !\is_dir($dir)) {
            return [
                'ok' => false,
                'path' => $path,
                'message' => 'conf_dir_unavailable',
            ];
        }
        $cookie = FpcPierceStamp::COOKIE_NAME;
        $query = FpcPierceStamp::QUERY_NAME;
        // CookieScope may wire as w_weline_fpc_pierce_w0 — $cookie_<base> misses that.
        $body = <<<NGINX
# Generated by FpcPierceNginxMapWriter — do not hand-edit.
map \$http_cookie \$wls_fpc_pierce_cookie_ok {
    default 0;
    "~*(?:^|;\\s*){$cookie}(?:_w\\d+)?={$secret}(?:;|\$)" 1;
}
map \$arg_{$query} \$wls_fpc_pierce_arg_ok {
    default 0;
    "{$secret}" 1;
}
map "\$wls_fpc_pierce_cookie_ok\$wls_fpc_pierce_arg_ok" \$wls_fpc_pierce_ok {
    default 0;
    "~1" 1;
}

NGINX;
        $previous = \is_file($path) ? (string)@\file_get_contents($path) : null;
        $tmp = $dir . \DIRECTORY_SEPARATOR . '.tmp-fpc-pierce-' . \bin2hex(\random_bytes(6));
        if (@\file_put_contents($tmp, $body, \LOCK_EX) === false) {
            @\unlink($tmp);

            return [
                'ok' => false,
                'path' => $path,
                'message' => 'temp_write_failed',
            ];
        }
        if (!@\rename($tmp, $path)) {
            @\unlink($tmp);
            if (\is_string($previous)) {
                @\file_put_contents($path, $previous, \LOCK_EX);
            }

            return [
                'ok' => false,
                'path' => $path,
                'message' => 'publish_rename_failed',
            ];
        }
        @\chmod($path, 0600);

        return [
            'ok' => true,
            'path' => $path,
            'message' => 'published',
        ];
    }
}
