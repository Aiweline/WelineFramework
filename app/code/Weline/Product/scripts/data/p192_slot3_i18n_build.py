# Keys order matches /tmp/p192_en_keys.json

def pack(*vals: str) -> dict[str, str]:
    assert len(vals) == len(KEYS), f'expected {len(KEYS)} got {len(vals)}'
    out = {}
    for k, v in zip(KEYS, vals):
        if v is None or v == k:
            continue
        out[k] = v
    return out


